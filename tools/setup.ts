#!/usr/bin/env bun
// bun tools/setup.ts — link the runtime the applet builds against.
//
// The applet is compiled by Pocket Shell's CLI and its pinned PocketJS, but
// its imports resolve from this repository: "solid-js" or
// "@pocketjs/framework/ui" in app/, or "@pocket-shell/runtime/link" in
// vendor/applets/lib, walk up to ./node_modules. So the packages that PocketJS
// checkout installed are linked here instead of installed a second time,
// which also keeps one copy of Solid: two would give the app a reactive graph
// the framework does not own. (pocket-nexus/applets does the same, tools/setup.ts.)
import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { POCKET_SHELL, POCKET_SHELL_CLI, POCKETJS, ROOT } from "./paths.ts";

if (!existsSync(POCKET_SHELL_CLI)) throw new Error(`pocket-lody setup: no Pocket Shell at ${POCKET_SHELL}: git submodule update --init vendor/pocket-shell`);
if (!existsSync(resolve(POCKETJS, "node_modules/solid-js"))) {
  throw new Error(`pocket-lody setup: no installed PocketJS at ${POCKETJS}: git -C ${POCKET_SHELL} submodule update --init vendor/pocketjs && bun install --cwd ${POCKETJS} --frozen-lockfile`);
}
const pinned = readFileSync(resolve(POCKETJS, ".bun-version"), "utf8").trim();
if (Bun.version !== pinned) throw new Error(`pocket-lody setup: the PocketJS at ${POCKETJS} runs on Bun ${pinned}; this is Bun ${Bun.version}`);

const links = new Map<string, string>([
  ["node_modules/@pocketjs/framework", POCKETJS],
  ["node_modules/@pocket-shell/runtime", resolve(POCKET_SHELL, "runtime")],
  ["node_modules/solid-js", resolve(POCKETJS, "node_modules/solid-js")],
  ["node_modules/bun-types", resolve(POCKETJS, "node_modules/bun-types")],
  ["node_modules/typescript", resolve(POCKETJS, "node_modules/typescript")],
  ["node_modules/@types/bun", resolve(POCKETJS, "node_modules/@types/bun")],
  ["node_modules/@napi-rs/canvas", resolve(POCKETJS, "node_modules/@napi-rs/canvas")],
  ["node_modules/opentype.js", resolve(POCKETJS, "node_modules/opentype.js")],
]);
for (const [destination, target] of links) {
  if (!existsSync(target)) throw new Error(`pocket-lody setup: missing ${target}`);
  const link = resolve(ROOT, destination);
  mkdirSync(dirname(link), { recursive: true });
  rmSync(link, { recursive: true, force: true });
  symlinkSync(relative(dirname(link), target), link, "dir");
}

// Pocket Shell's own modules find "@pocketjs/framework/*" through its links
await Bun.spawn([process.execPath, resolve(POCKET_SHELL, "scripts/setup.ts")], { cwd: POCKET_SHELL, stdout: "inherit", stderr: "inherit" }).exited;

// a clean PocketJS has no style table until its first build; the empty one is the honest state before it
const styles = resolve(POCKETJS, "framework/src/styles.generated.ts");
if (!existsSync(styles)) writeFileSync(styles, "// Generated by PocketJS builds.\nexport const STYLE_IDS: Record<string, number> = {};\n");
console.log("pocket-lody setup: runtime links ready");
